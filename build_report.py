def set_page_margins(doc, top=2.5, bottom=2.0, left=3.0, right=1.5):
    """Поля в сантиметрах (ГОСТ 7.32)."""
    for section in doc.sections:
        section.top_margin = Cm(top)
        section.bottom_margin = Cm(bottom)
        section.left_margin = Cm(left)
        section.right_margin = Cm(right)


def paragraph_format(para, font_name=TNR, font_size=14,
                      bold=False, italic=False, color=None,
                      alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
                      space_before=0, space_after=6,
                      line_spacing=1.5):
    """Применяет форматирование ко всему абзацу."""
    pf = para.paragraph_format
    pf.alignment = alignment
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = line_spacing

    for run in para.runs:
        run.font.name = font_name
        run.font.size = Pt(font_size)
        run.font.bold = bold
        run.font.italic = italic
        if color:
            run.font.color.rgb = RGBColor(*color)
        # Кириллические шрифты требуют явного указания восточного шрифта
        r_pr = run._r.get_or_add_rPr()
        r_fonts = OxmlElement('w:rFonts')
        r_fonts.set(qn('w:eastAsia'), font_name)
        r_pr.insert(0, r_fonts)


def add_body(doc, text, font_name=TNR, font_size=14,
             bold=False, italic=False,
             alignment=WD_ALIGN_PARAGRAPH.JUSTIFY,
             space_after=6, first_line_indent=True):
    """Добавляет абзац основного текста."""
    para = doc.add_paragraph()
    if first_line_indent:
        para.paragraph_format.first_line_indent = Cm(1.25)
    run = para.add_run(text)
    paragraph_format(para, font_name=font_name, font_size=font_size,
                     bold=bold, italic=italic, alignment=alignment,
                     space_after=space_after)
    return para


def add_heading(doc, text, level=1):
    """
    Заголовки: Times New Roman жирный.
    level=1 → 16pt, по центру
    level=2 → 14pt, по левому
    level=3 → 13pt, по левому
    """
    para = doc.add_paragraph()
    run = para.add_run(text)
    sizes = {1: 16, 2: 14, 3: 13}
    aligns = {
        1: WD_ALIGN_PARAGRAPH.CENTER,
        2: WD_ALIGN_PARAGRAPH.LEFT,
        3: WD_ALIGN_PARAGRAPH.LEFT,
    }
    paragraph_format(para, font_name=TNR, font_size=sizes[level],
                     bold=True, alignment=aligns[level],
                     space_before=12, space_after=6, line_spacing=1.5)
    para.paragraph_format.first_line_indent = Pt(0)
    return para


def add_page_break(doc):
    from docx.enum.text import WD_BREAK
    para = doc.add_paragraph()
    run = para.add_run()
    run.add_break(WD_BREAK.PAGE)
    return para


def add_image(doc, filename, caption_num, caption_text, width_cm=15):
    """Вставляет скриншот с подписью."""
    img_path = os.path.join(SCREENSHOTS_DIR, filename)
    if not os.path.exists(img_path):
        add_body(doc, f'[СКРИНШОТ ОТСУТСТВУЕТ: {filename}]', italic=True)
        return
    para = doc.add_paragraph()
    para.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = para.add_run()
    run.add_picture(img_path, width=Cm(width_cm))

    cap = doc.add_paragraph()
    cap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(10)
    r = cap.add_run(f'Рисунок {caption_num} — {caption_text}')
    r.font.name = TNR
    r.font.size = Pt(12)
    r.font.italic = True


def add_competence_table(doc, rows):
    """
    rows — список кортежей (навык, компетенция_текст)
    """
    table = doc.add_table(rows=1 + len(rows), cols=2)
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER

    # Заголовок таблицы
    hdr = table.rows[0].cells
    for i, txt in enumerate(['Полученные навыки', 'Содержание компетенции']):
        hdr[i].text = txt
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for run in p.runs:
            run.font.name = TNR
            run.font.size = Pt(12)
            run.font.bold = True

    for idx, (skill, comp) in enumerate(rows, start=1):
        cells = table.rows[idx].cells
        cells[0].text = skill
        cells[1].text = comp
        for cell in cells:
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            for run in p.runs:
                run.font.name = TNR
                run.font.size = Pt(12)

    # Ширина колонок
    from docx.shared import Cm as C
    for row in table.rows:
        row.cells[0].width = C(8)
        row.cells[1].width = C(8)

    doc.add_paragraph()  # отступ после таблицы


